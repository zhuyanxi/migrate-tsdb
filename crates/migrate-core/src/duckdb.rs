//! DuckDB integration.
//!
//! The migration itself writes Parquet (DuckDB's native external format).
//! This module emits a load script and optionally executes it through the
//! `duckdb` CLI. Avoiding a link-time dependency on libduckdb keeps the binary
//! small and the build fast, while `read_parquet` gives DuckDB full pushdown.

use std::path::{Path, PathBuf};

use crate::error::{Error, Result};

pub const LOAD_SQL_FILE: &str = "load_duckdb.sql";

fn sql_escape(s: &str) -> String {
    s.replace('\'', "''")
}

fn has_parquet(dir: &Path) -> bool {
    let Ok(rd) = std::fs::read_dir(dir) else {
        return false;
    };
    rd.flatten().any(|e| {
        e.path()
            .extension()
            .map(|x| x == "parquet")
            .unwrap_or(false)
    })
}

pub fn generate_sql(out_dir: &Path) -> String {
    let root = out_dir
        .canonicalize()
        .unwrap_or_else(|_| out_dir.to_path_buf());
    let root = sql_escape(&root.display().to_string());
    let mut sql = String::new();
    sql.push_str("-- Generated by tsdb-migrate. Requires DuckDB >= 0.10.\n");
    sql.push_str("-- Each block is stored as a Hive partition (block=<ULID>).\n\n");

    for (table, dir) in [
        ("series", "series"),
        ("samples", "samples"),
        ("histograms", "histograms"),
    ] {
        let dataset = out_dir.join("blocks");
        let any = std::fs::read_dir(&dataset)
            .map(|rd| {
                rd.flatten()
                    .any(|e| e.path().is_dir() && has_parquet(&e.path().join(dir)))
            })
            .unwrap_or(false);
        if any {
            sql.push_str(&format!(
                "CREATE OR REPLACE TABLE {table} AS\nSELECT * FROM read_parquet('{root}/blocks/*/{dir}/*.parquet', hive_partitioning = true);\n\n"
            ));
        } else {
            sql.push_str(&format!(
                "-- No {dir} files were produced; table `{table}` is not created.\n\n"
            ));
        }
    }

    sql.push_str(
        "-- Convenience: one row per migrated block.\n\
         -- CREATE VIEW block_summary AS\n\
         -- SELECT block, count(*) AS series FROM series GROUP BY block;\n",
    );
    sql
}

pub fn write_sql(out_dir: &Path) -> Result<PathBuf> {
    let path = out_dir.join(LOAD_SQL_FILE);
    std::fs::write(&path, generate_sql(out_dir))?;
    Ok(path)
}

fn duckdb_available() -> bool {
    std::process::Command::new("duckdb")
        .arg("--version")
        .stdout(std::process::Stdio::null())
        .stderr(std::process::Stdio::null())
        .status()
        .map(|s| s.success())
        .unwrap_or(false)
}

/// Runs the generated load script with the DuckDB CLI.
pub fn execute(out_dir: &Path, db_path: &Path) -> Result<()> {
    let sql_path = write_sql(out_dir)?;
    if !duckdb_available() {
        return Err(Error::sink(
            "duckdb CLI not found in PATH; load_duckdb.sql was generated, run it manually",
        ));
    }
    let sql = std::fs::read_to_string(&sql_path)?;
    let mut child = std::process::Command::new("duckdb")
        .arg(db_path)
        .arg("-c")
        .arg(sql)
        .stdout(std::process::Stdio::inherit())
        .stderr(std::process::Stdio::inherit())
        .spawn()?;
    let status = child.wait()?;
    if !status.success() {
        return Err(Error::sink(format!(
            "duckdb exited with status {status} while loading {}",
            sql_path.display()
        )));
    }
    Ok(())
}

